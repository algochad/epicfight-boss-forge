def text_size(text: str, scale: int = 1) -> Tuple[int, int]:
    return (len(text) * (GLYPH_W + 1) - 1) * scale, GLYPH_H * scale


def draw_text(c: Canvas, x: int, y: int, text: str, scale: int = 1, fg=(235, 238, 245), plate=(0, 0, 0, 150), pad: int = 2) -> None:
    """Text (upper case, digits and `. , : = + - / ( ) _ % | < > # ?`) on a translucent plate; top-left corner at (x, y)."""
    text = str(text).upper()
    w, h = text_size(text, scale)
    if plate is not None:
        fill_rect(c, x - pad, y - pad, w + 2 * pad, h + 2 * pad, plate[:3], plate[3] / 255.0)
    cx = x
    for ch in text:
        rows = _GLYPH_ROWS.get(ch, _GLYPH_ROWS["?"])
        for gy, row in enumerate(rows):
            for gx, bit in enumerate(row):
                if bit == "#":
                    fill_rect(c, cx + gx * scale, y + gy * scale, scale, scale, fg, 1.0)
        cx += (GLYPH_W + 1) * scale


def fill_rect(c: Canvas, x: int, y: int, w: int, h: int, rgb, alpha: float = 1.0) -> None:
    x0, y0, x1, y1 = max(0, x), max(0, y), min(c.w, x + w), min(c.h, y + h)
    if x1 <= x0 or y1 <= y0:
        return
    d = c.data
    if alpha >= 0.999:
        px = bytes((rgb[0], rgb[1], rgb[2], 255)) * (x1 - x0)
        for yy in range(y0, y1):
            o = (yy * c.w + x0) * 4
            d[o:o + len(px)] = px
        return
    ia = 1.0 - alpha
    ra, ga, ba = rgb[0] * alpha, rgb[1] * alpha, rgb[2] * alpha
    for yy in range(y0, y1):
        o = (yy * c.w + x0) * 4
        for _ in range(x1 - x0):
            d[o] = int(d[o] * ia + ra)
            d[o + 1] = int(d[o + 1] * ia + ga)
            d[o + 2] = int(d[o + 2] * ia + ba)
            o += 4


def blend_pixel(c: Canvas, x: int, y: int, rgb, alpha: float) -> None:
    if 0 <= x < c.w and 0 <= y < c.h:
        o = (y * c.w + x) * 4
        d = c.data
        ia = 1.0 - alpha
        d[o] = int(d[o] * ia + rgb[0] * alpha)
        d[o + 1] = int(d[o + 1] * ia + rgb[1] * alpha)
        d[o + 2] = int(d[o + 2] * ia + rgb[2] * alpha)


def _blend_table(value: float, alpha: float) -> bytes:
    ia = 1.0 - alpha
    return bytes(min(255, int(v * ia + value * alpha)) for v in range(256))


def _blend_run(c: Canvas, start: int, end_exclusive: int, step: int, rgb, alpha: float) -> None:
    """Blend `rgb` over the pixels whose first byte offsets run start, start+step, ... (channel-wise translate, C speed)."""
    d = c.data
    for k in range(3):
        sl = slice(start + k, end_exclusive + k, step)
        d[sl] = bytes(d[sl]).translate(_blend_table(rgb[k], alpha))


def _clip_line(x0: float, y0: float, x1: float, y1: float, w: int, h: int):
    """Liang-Barsky clip of a segment to [0, w-1] x [0, h-1]; None when fully outside."""
    t0, t1 = 0.0, 1.0
    dx, dy = x1 - x0, y1 - y0
    for p, q in ((-dx, x0), (dx, w - 1 - x0), (-dy, y0), (dy, h - 1 - y0)):
        if p == 0:
            if q < 0:
                return None
        else:
            r = q / p
            if p < 0:
                if r > t1:
                    return None
                t0 = max(t0, r)
            else:
                if r < t0:
                    return None
                t1 = min(t1, r)
    return x0 + t0 * dx, y0 + t0 * dy, x0 + t1 * dx, y0 + t1 * dy


def draw_line(c: Canvas, x0: float, y0: float, x1: float, y1: float, rgb, alpha: float = 1.0, width: int = 1) -> None:
    """Anti-alias free line clipped to the canvas; `width` 2 draws a 2 pixel wide line. Horizontal and vertical lines
    are blended per row / column with byte tables."""
    clipped = _clip_line(x0, y0, x1, y1, c.w, c.h)
    if clipped is None:
        return
    x0, y0, x1, y1 = clipped
    dx, dy = x1 - x0, y1 - y0
    if abs(dy) < 0.5:
        y = int(round((y0 + y1) / 2.0))
        xa, xb = int(round(min(x0, x1))), int(round(max(x0, x1)))
        for yy in range(y, y + width):
            if 0 <= yy < c.h:
                _blend_run(c, (yy * c.w + xa) * 4, (yy * c.w + xb) * 4 + 1, 4, rgb, alpha)
        return
    if abs(dx) < 0.5:
        x = int(round((x0 + x1) / 2.0))
        ya, yb = int(round(min(y0, y1))), int(round(max(y0, y1)))
        for xx in range(x, x + width):
            if 0 <= xx < c.w:
                _blend_run(c, (ya * c.w + xx) * 4, (yb * c.w + xx) * 4 + 1, c.w * 4, rgb, alpha)
        return
    n = int(max(abs(dx), abs(dy))) + 1
    for i in range(n + 1):
        t = i / float(n)
        px, py = int(round(x0 + dx * t)), int(round(y0 + dy * t))
        blend_pixel(c, px, py, rgb, alpha)
        if width > 1:
            if abs(dx) >= abs(dy):
                blend_pixel(c, px, py + 1, rgb, alpha)
            else:
                blend_pixel(c, px + 1, py, rgb, alpha)


def solid(w: int, h: int, rgb) -> Canvas:
    c = Canvas(w, h)
    c.fill((rgb[0], rgb[1], rgb[2], 255))
    return c


def over(dst: Canvas, src: Canvas, dx: int = 0, dy: int = 0) -> None:
    """Straight-alpha `src` composited over the (opaque) `dst`; only pixels with alpha > 0 are touched."""
    sd, dd = src.data, dst.data
    alpha = sd[3::4]
    for i in compress(range(len(alpha)), alpha):
        x, y = i % src.w + dx, i // src.w + dy
        if not (0 <= x < dst.w and 0 <= y < dst.h):
            continue
        a = alpha[i]
        s, d = i * 4, (y * dst.w + x) * 4
        if a == 255:
            dd[d:d + 3] = sd[s:s + 3]
        else:
            ia = 255 - a
            dd[d] = (sd[s] * a + dd[d] * ia + 127) // 255
            dd[d + 1] = (sd[s + 1] * a + dd[d + 1] * ia + 127) // 255
            dd[d + 2] = (sd[s + 2] * a + dd[d + 2] * ia + 127) // 255


def paste(dst: Canvas, src: Canvas, x: int, y: int) -> None:
    """Opaque copy of `src` into `dst` (row slices)."""
    for r in range(src.h):
        ty = y + r
        if not 0 <= ty < dst.h:
            continue
        x0, x1 = max(0, x), min(dst.w, x + src.w)
        if x1 <= x0:
            continue
        s = (r * src.w + (x0 - x)) * 4
        d = (ty * dst.w + x0) * 4
        dst.data[d:d + (x1 - x0) * 4] = src.data[s:s + (x1 - x0) * 4]


def lighten(rgb, k: float) -> Tuple[int, int, int]:
    return tuple(min(255, int(v + (255 - v) * k)) if k >= 0 else int(v * (1 + k)) for v in rgb)  # type: ignore[return-value]


# ------------------------------------------------------------------------------------------- camera projection
class Cam:
    """Projection of a camera reported by Blender (`camera_meta`): world point -> pixel."""

    def __init__(self, meta: dict):
        self.w, self.h = int(meta["width"]), int(meta["height"])
        self.ortho = meta["type"] == "ORTHO"
        self.ortho_scale = float(meta["ortho_scale"])
        self.focal_px = float(meta["lens"]) / float(meta["sensor_width"]) * self.w
        self.world = tuple(v for row in meta["matrix_world"] for v in row)
        self.inv = efanim.mat_inv(self.world)

    @property
    def px_per_block(self) -> float:
        return self.w / self.ortho_scale if self.ortho else float("nan")

    def project(self, p: Sequence[float]) -> Tuple[float, float]:
        cx, cy, cz = efanim.mat_apply(self.inv, p)
        if self.ortho:
            s = self.w / self.ortho_scale
            return self.w / 2.0 + cx * s, self.h / 2.0 - cy * s
        d = max(-cz, 1e-6)
        return self.w / 2.0 + self.focal_px * cx / d, self.h / 2.0 - self.focal_px * cy / d


def decorate(img: Canvas, cam: Cam, bg, grid: bool = True, ground_line: bool = True) -> None:
    """Ground grid (1 block cells on z = 0) and the ground line, drawn on the background only."""
    gl = lighten(bg, 0.16)
    ax = lighten(bg, 0.34)
    reach = int(math.ceil(cam.ortho_scale * (1.0 if cam.ortho else 1.2))) + 1
    seen = set()

    def seg(a, b, col, alpha):
        (x0, y0), (x1, y1) = cam.project(a), cam.project(b)
        if math.hypot(x1 - x0, y1 - y0) < 2.0:
            return
        key = (round(x0), round(y0), round(x1), round(y1))
        if key not in seen:  # edge-on views collapse the whole grid onto one line: draw it once
            seen.add(key)
            draw_line(img, x0, y0, x1, y1, col, alpha)

    if grid:
        for i in range(-reach, reach + 1):
            col = ax if i == 0 else gl
            a = 0.55 if i == 0 else 0.35
            seg((i, -reach, 0.0), (i, reach, 0.0), col, a)
            seg((-reach, i, 0.0), (reach, i, 0.0), col, a)
    if ground_line:
        (x0, y0), (x1, y1) = cam.project((-reach, 0.0, 0.0)), cam.project((reach, 0.0, 0.0))
        if abs(y1 - y0) < 3:  # edge-on: the grid collapsed onto a line, make it a clear ground line
            draw_line(img, 0, y0, img.w, y0, lighten(bg, 0.45), 0.8, 2)


def scale_bar(img: Canvas, cam: Cam, bg) -> None:
    """1 block bar at the left edge: vertical (height of the character) or, when looking down, horizontal."""
    if not cam.ortho:
        return
    ppb = cam.px_per_block
    (ox, oy), (ux, uy) = cam.project((0.0, 0.0, 0.0)), cam.project((0.0, 0.0, 1.0))
    col = (230, 230, 120)
    x = 18
    if abs(uy - oy) > 0.5 * ppb:
        length = abs(uy - oy)
        y1 = img.h - 28
        y0 = y1 - length
        draw_line(img, x, y0, x, y1, col, 1.0, 2)
        for t in (0.0, 0.25, 0.5, 0.75, 1.0):
            yy = y1 - length * t
            draw_line(img, x - 4, yy, x + 5, yy, col, 1.0)
        draw_text(img, x + 9, int(y0) + 2, "1 BLOCK", 1)
    else:
        y = img.h - 26
        draw_line(img, x, y, x + ppb, y, col, 1.0, 2)
        for t in (0.0, 0.5, 1.0):
            draw_line(img, x + ppb * t, y - 4, x + ppb * t, y + 5, col, 1.0)
        draw_text(img, x, y - 16, "1 BLOCK", 1)


def compose_view(raw: Canvas, cam: Cam, bg, label: str, grid: bool = True, cache: Optional[dict] = None) -> Canvas:
    """Background (+ ground grid and scale bar), the transparent render over it, then the label. `cache` (a dict)
    keeps the drawn background per camera so the frames of one view share it."""
    key = (raw.w, raw.h, cam.ortho, round(cam.ortho_scale, 5), tuple(round(v, 4) for v in cam.world), tuple(bg), grid)
    base = cache.get(key) if cache is not None else None
    if base is None:
        base = solid(raw.w, raw.h, bg)
        if grid:
            decorate(base, cam, bg)
            scale_bar(base, cam, bg)
        if cache is not None:
            cache[key] = base
    img = Canvas(base.w, base.h, bytearray(base.data))
    over(img, raw)
    draw_text(img, 6, 6, label, 2 if raw.w >= 420 else 1)
    return img


# ------------------------------------------------------------------------------------------- montage
def montage(cells: Sequence[Canvas], cols: int, gap: int = 6, bg=(12, 14, 20), title: Optional[str] = None) -> Canvas:
    if not cells:
        return solid(8, 8, bg)
    cols = max(1, min(int(cols), len(cells)))
    rows = (len(cells) + cols - 1) // cols
    cw = max(c.w for c in cells)
    ch = max(c.h for c in cells)
    head = 22 if title else 0
    out = solid(cols * cw + (cols + 1) * gap, rows * ch + (rows + 1) * gap + head, bg)
    if title:
        draw_text(out, gap + 2, 7, title, 1, plate=None)
    for i, c in enumerate(cells):
        r, k = divmod(i, cols)
        paste(out, c, gap + k * (cw + gap) + (cw - c.w) // 2, head + gap + r * (ch + gap) + (ch - c.h) // 2)
    return out


# ------------------------------------------------------------------------------------------- reference comparison
def reference_cameras(views: Dict[str, Any], names: Sequence[str]) -> List[dict]:
    """Explicit Blender cameras that reproduce the calibration of reference views (orthographic, pixel aligned)."""
    cams = []
    for name in names:
        v = views[name]
        x0, y0, x1, y1 = v.crop
        w, h = x1 - x0, y1 - y0
        u, vv = v.unproject(x0 + w / 2.0, y0 + h / 2.0)  # model coordinates of the crop centre
        if name in ("front", "back"):
            target = [u, 0.0, vv]  # model x = storage x, model y = storage z
        else:
            target = [0.0, -u, vv]  # model z = -storage y
        az = {"front": 0.0, "back": 180.0, "right": -90.0, "left": 90.0}[name]
        cams.append({"name": "ref_" + name, "azimuth": az, "elevation": 0.0, "target": target, "ortho": True,
                     "ortho_scale": w / v.px_per_block, "width": w, "height": h, "lens": 50.0})
    return cams


def _reference_crop(v) -> Canvas:
    x0, y0, x1, y1 = v.crop
    c = Canvas(x1 - x0, y1 - y0)
    for r in range(y1 - y0):
        s = ((y0 + r) * v.width + x0) * 4
        c.data[r * c.w * 4:(r + 1) * c.w * 4] = v.rgba[s:s + c.w * 4]
    return c


def _mask_crop(v) -> bytes:
    x0, y0, x1, y1 = v.crop
    w = x1 - x0
    out = bytearray()
    for r in range(y1 - y0):
        out += v.mask[(y0 + r) * v.width + x0:(y0 + r) * v.width + x0 + w]
    return bytes(out)


def silhouette_metrics(render_alpha: bytes, ref_mask: bytes) -> Dict[str, Any]:
    """IoU and areas of two same-size silhouettes (alpha > 127 / mask != 0)."""
    inter = a_only = b_only = 0
    for a, m in zip(render_alpha, ref_mask):
        ra, rm = a > 127, m != 0
        if ra and rm:
            inter += 1
        elif ra:
            a_only += 1
        elif rm:
            b_only += 1
    union = inter + a_only + b_only
    return {"iou": round(inter / union, 4) if union else 0.0, "render_px": inter + a_only, "reference_px": inter + b_only,
            "render_only_px": a_only, "reference_only_px": b_only}


def reference_cell(name: str, view, raw: Canvas, cam: Cam, bg, grid: bool) -> Tuple[Canvas, Dict[str, Any]]:
    """[reference | render | silhouette difference] for one reference view, at the reference's pixel scale."""
    ref = _reference_crop(view)
    ref_bg = solid(ref.w, ref.h, bg)
    over(ref_bg, ref)
    mask = _mask_crop(view)
    rend = solid(raw.w, raw.h, bg)
    if grid:
        decorate(rend, cam, bg)
    over(rend, raw)
    alpha = bytes(raw.data[3::4])
    met = silhouette_metrics(alpha, mask)
    diff = solid(raw.w, raw.h, (18, 20, 28))
    d = diff.data
    for i, (a, m) in enumerate(zip(alpha, mask)):
        ra, rm = a > 127, m != 0
        if ra and rm:
            col = (118, 122, 134)
        elif ra:
            col = (60, 205, 235)
        elif rm:
            col = (235, 70, 70)
        else:
            continue
        d[i * 4:i * 4 + 3] = bytes(col)
    sc = 2 if raw.w >= 300 else 1
    draw_text(ref_bg, 6, 6, "REF " + name.upper(), sc)
    draw_text(rend, 6, 6, "RENDER %s  %.0f PX/BLOCK" % (name.upper(), cam.px_per_block), sc)
    draw_text(diff, 6, 6, "IOU %.3f  RED=REF ONLY  CYAN=RENDER ONLY" % met["iou"], 1)
    return montage([ref_bg, rend, diff], 3, gap=4), met


# ------------------------------------------------------------------------------------------- source resolution
class Source:
    """What the Blender run shows: a bundle (+ texture) or an already built .blend."""

    def __init__(self, kind: str, ident: str):
        self.kind, self.id = kind, ident
        self.bundle: Optional[Path] = None
        self.blend: Optional[Path] = None
        self.texture: Optional[Path] = None
        self.spec_path: Optional[Path] = None
        self.norm: Optional[dict] = None
        self.warnings: List[Any] = []
        self.notes: List[str] = []

    def to_dict(self) -> dict:
        return {"kind": self.kind, "id": self.id, "bundle": str(self.bundle) if self.bundle else None,
                "blend": str(self.blend) if self.blend else None, "texture": str(self.texture) if self.texture else None,
                "spec": str(self.spec_path) if self.spec_path else None, "notes": self.notes}


def _looks_like_mesh(path: Path) -> bool:
    try:
        with open(str(path), "r", encoding="utf-8") as f:
            head = f.read(4096)
    except (OSError, UnicodeDecodeError):
        return False
    return '"vertices"' in head


def _bundle_id(path: Path) -> str:
    n = path.name
    for suf in (".efmesh.json", ".json"):
        if n.endswith(suf):
            return n[: -len(suf)]
    return n


def bundle_mesh_file(bundle: Path) -> Path:
    """The mesh JSON of a bundle: the path itself, or the only `*.efmesh.json` (else the only `*.json`) of a directory."""
    if not bundle.is_dir():
        return bundle
    for pat in ("*.efmesh.json", "*.json"):
        found = sorted(p for p in bundle.glob(pat) if not p.name.endswith(".meshmeta.json"))
        if len(found) == 1:
            return found[0]
        if len(found) > 1:
            raise _err("/source", "ambiguous_bundle", "%s holds several meshes (%s); pass one <id>.efmesh.json" % (bundle, ", ".join(p.name for p in found)))
    raise _err("/source", "file_not_found", "no *.efmesh.json in %s" % bundle)


def find_bundle_texture(bundle: Path) -> Optional[Path]:
    """`<id>.png` next to the mesh file of a bundle, if it exists."""
    p = bundle.with_name(_bundle_id(bundle) + ".png")
    return p if p.is_file() else None


def _skin_spec(n: dict, out: Path, cache: Path, offline: bool, ef_jar: Optional[str]) -> Tuple[Path, dict]:
    """Paint the spec's texture with `skin` into out/skin and return its path."""
    from . import skin
    ctx = S.make_context(out / "skin", n["mod_id"], "com.bossforge." + n["mod_id"], cache, offline=offline, ef_jar=ef_jar)
    files, _lang, report = skin.generate_with_report(n, ctx)
    for f in files:
        p = ctx.project_root / f.relpath
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(f.data)
    tex = Path(report["texture"]["path"])
    if not tex.is_absolute():
        tex = ctx.project_root / tex
    return tex, report


def resolve_source(source: str, out: Path, texture: Optional[str], cache: Path, offline: bool, ef_jar: Optional[str]) -> Source:
    p = Path(source).expanduser()
    if not p.exists():
        raise _err("/source", "file_not_found", "no such file or directory: %s" % source)
    tex = Path(texture).expanduser().resolve() if texture else None
    if tex is not None and not tex.is_file():
        raise _err("/texture", "file_not_found", "texture not found: %s" % texture)
    if p.is_dir() or p.name.endswith(".efmesh.json") or (p.suffix == ".json" and _looks_like_mesh(p)):
        mesh = bundle_mesh_file(p)
        s = Source("bundle", _bundle_id(mesh))
        s.bundle = mesh.resolve()
        s.texture = tex or find_bundle_texture(mesh)
        if s.texture is None:
            s.notes.append("no texture: showing the importer's flat group tints (pass --texture PNG)")
        return s
    if p.suffix == ".blend":
        s = Source("blend", p.stem)
        s.blend = p.resolve()
        s.texture = tex
        if tex is None:
            s.notes.append("no texture given: showing the materials stored in the .blend")
        return s
    if p.suffix != ".json":
        raise _err("/source", "unsupported_source", "%s is not a spec .json, a mesh bundle, an EF mesh JSON or a .blend" % source)
    raw = S.load(p)
    n, errs, warns = S.check(raw)
    if errs:
        raise BossForgeError(errs[0].path, errs[0].code, "spec is invalid: " + "; ".join("%s [%s] %s" % (e.path, e.code, e.message) for e in errs[:4]))
    s = Source("spec", str(n["id"]))
    s.spec_path = p.resolve()
    s.norm = n
    s.warnings = [w.to_dict() for w in warns]
    template = (n.get("derived") or {}).get("template")
    if tex is None:
        tex, report = _skin_spec(n, out, cache, offline, ef_jar)
        s.warnings += list(report.get("warnings", []))
        s.notes.append("texture painted by `skin` (%s)" % tex)
    s.texture = tex
    mesh_block = n.get("mesh") or raw.get("mesh")
    if mesh_block:
        base = Path(n.get("_spec_dir") or p.resolve().parent)
        f = Path(mesh_block["file"])
        s.bundle = (f if f.is_absolute() else base / f).resolve()
        if not s.bundle.is_file():
            raise _err("/mesh/file", "file_not_found", "mesh bundle %s not found" % s.bundle)
    elif n.get("shape"):
        from . import efmodel, shape
        model = shape.build_model(n, S.make_context(out / "skin", n["mod_id"], "com.bossforge." + n["mod_id"], cache, offline=offline, ef_jar=ef_jar))
        problems = efmodel.check_mesh_json(model.mesh_json)
        if problems:
            raise _err("/shape", "bad_mesh", "generated mesh is invalid: " + "; ".join(problems[:4]))
        mdir = out / "model"
        mdir.mkdir(parents=True, exist_ok=True)
        s.bundle = mdir / ("%s.efmesh.json" % n["id"])
        s.bundle.write_text(efmodel.dumps(model.mesh_json) + "\n", encoding="utf-8")
        s.notes.append("box model built with `shape` (%d boxes)" % len(model.boxes))
    else:
        if template == "iron_golem":
            raise _err("/body/template", "unsupported_template", "the stock iron golem mesh has its own armature; `blender view` supports the EF biped rig only")
        from . import efassets
        ref = S.data("versions")["epicfight"]["assets_ref"]
        s.bundle = efassets.mesh_file("biped", cache, ref, ef_jar, offline).resolve()
        s.notes.append("stock EF biped mesh")
    return s


