def parse_list(text: Optional[str], allowed: Optional[Sequence[str]], path: str, default: Sequence[str]) -> List[str]:
    if text is None or not str(text).strip():
        return list(default)
    out = []
    for item in str(text).split(","):
        item = item.strip()
        if not item:
            continue
        if allowed is not None and item not in allowed:
            raise _err(path, "unknown_value", "%r is not one of %s" % (item, ", ".join(allowed)))
        if item not in out:
            out.append(item)
    return out


def parse_times(text: Optional[str]) -> List[float]:
    if text is None or not str(text).strip():
        return [0.0]
    out = []
    for item in str(text).split(","):
        item = item.strip()
        if not item:
            continue
        try:
            t = float(item)
        except ValueError:
            raise _err("/at", "bad_time", "%r is not a number of seconds" % item)
        if not math.isfinite(t) or t < 0:
            raise _err("/at", "bad_time", "times must be finite and >= 0, got %r" % item)
        out.append(t)
    if not out:
        raise _err("/at", "bad_time", "--at needs at least one time")
    if len(out) > 12:
        raise _err("/at", "bad_time", "at most 12 times (got %d)" % len(out))
    return out


def parse_color(text: str) -> Tuple[int, int, int]:
    t = str(text).strip().lstrip("#")
    if len(t) == 3:
        t = "".join(c * 2 for c in t)
    try:
        if len(t) != 6:
            raise ValueError
        return (int(t[0:2], 16), int(t[2:4], 16), int(t[4:6], 16))
    except ValueError:
        raise _err("/bg", "bad_color", "%r is not a #rrggbb colour" % text)


def joint_names() -> List[str]:
    return [j["name"] for j in sorted(S.data("rigs")["biped"]["joints"], key=lambda j: j["index"])]


def resolve_joint(name: str) -> str:
    """bossforge bone name (arm_r, forearm_r, thigh_l, ...) or EF joint name (any case) -> EF joint name."""
    key = name.strip()
    bones = S.data("rigs")["biped"]["bones"]
    if key.lower() in bones:
        return bones[key.lower()]
    for j in joint_names():
        if j.lower() == key.lower():
            return j
    raise _err("/pose", "unknown_bone", "%r is not a bone: bossforge bones %s, EF joints %s" % (name, ", ".join(bones), ", ".join(joint_names())))


def parse_pose(text: Optional[str]) -> List[Tuple[str, str, float]]:
    """`arm_r=60,thigh_l=-35,head=z:40` -> [(joint, axis, degrees)]. A bare number rotates about the world X axis (the
    character's side axis: positive swings a limb forward, towards +Y); `x:`, `y:`, `z:` pick the world axis."""
    ops: List[Tuple[str, str, float]] = []
    if text is None or not str(text).strip():
        return ops
    for item in str(text).split(","):
        item = item.strip()
        if not item:
            continue
        if "=" not in item:
            raise _err("/pose", "bad_pose", "%r must look like arm_r=60 or head=z:40" % item)
        name, val = item.split("=", 1)
        axis = "X"
        v = val.strip()
        if ":" in v:
            ax, v = v.split(":", 1)
            ax = ax.strip().upper()
            if ax not in ("X", "Y", "Z"):
                raise _err("/pose", "bad_pose", "axis in %r must be x, y or z" % item)
            axis = ax
        try:
            deg = float(v)
        except ValueError:
            raise _err("/pose", "bad_pose", "%r: %r is not an angle in degrees" % (item, v))
        if not math.isfinite(deg) or abs(deg) > 360:
            raise _err("/pose", "bad_pose", "%r: angle must be within +-360 degrees" % item)
        ops.append((resolve_joint(name), axis, deg))
    return ops


def describe_pose(ops: Sequence[Tuple[str, str, float]]) -> str:
    if not ops:
        return "rest"
    return " ".join("%s %s%g" % (j.lower(), a.lower(), d) for j, a, d in ops)


# ------------------------------------------------------------------------------------------- frames
def plan_frames(views: Sequence[str], pose_ops: Sequence[Tuple[str, str, float]], pose_sheet: bool, sheet_views: Sequence[str],
                size: int, sheet_size: int, anim_frames: Sequence[dict], anim_label: str, extra_views: Sequence[str] = ()) -> List[dict]:
    """The frames Blender renders. `main` (rest or the --pose pose) gets `views` (+ reference cameras); the pose sheet
    and the animation frames get `sheet_views` at `sheet_size`. Frames with an identical pose are merged by id."""
    frames: List[dict] = []
    main_ops = [list(o) for o in pose_ops]
    frames.append({"id": "main", "label": describe_pose(pose_ops), "group": "main", "views": list(views) + list(extra_views), "size": size, "ops": main_ops})
    if pose_sheet:
        for pid, label, ops in POSE_SHEET:
            frames.append({"id": "ps_" + pid, "label": label, "group": "pose_sheet", "views": list(sheet_views), "size": sheet_size,
                           "ops": [list(o) for o in ops]})
        if pose_ops:
            frames.append({"id": "ps_custom", "label": describe_pose(pose_ops), "group": "pose_sheet", "views": list(sheet_views), "size": sheet_size,
                           "ops": main_ops})
    for i, af in enumerate(anim_frames):
        frames.append({"id": "an_%d" % i, "label": "%s t=%.2f" % (anim_label, af["t"]), "group": "anim", "views": list(sheet_views), "size": sheet_size,
                       "deltas": {k: [round(float(x), 9) for x in v] for k, v in af["deltas"].items()}, "t": af["t"]})
    return frames


