# ------------------------------------------------------------------------------------------- verification of the animation maths
def used_positions(mesh_json: dict) -> List[int]:
    """Positions that the Blender importer keeps (referenced by a non-degenerate triangle), sorted: Blender vertex i is
    JSON position used[i]."""
    used = set()
    for arr in mesh_json["vertices"]["parts"].values():
        a = arr["array"]
        for k in range(len(a) // 9):
            tri = [a[9 * k + 3 * c] for c in range(3)]
            if len(set(tri)) == 3:
                used.update(tri)
    return sorted(used)


def verify_frames(bundle: Path, clip: efanim.Clip, arm: efanim.Armature, frames: Sequence[dict], blender_frames: Dict[str, dict]) -> Dict[str, Any]:
    """Compare the vertices Blender deformed through `deltas` with the EF-exact pure-Python skinning of the same mesh JSON."""
    mesh_json = json.loads(bundle_mesh_file(bundle).read_text("utf-8"))
    pos, infl = efanim.mesh_influences(mesh_json)
    used = used_positions(mesh_json)
    wsum = [sum(w for _j, w in infl[i]) for i in used]
    rows = []
    worst = 0.0
    for fr in frames:
        if "t" not in fr:
            continue
        bf = blender_frames.get(fr["id"])
        if not bf or "positions" not in bf:
            continue
        mc = efanim.pose_matrices(arm, clip.sample(fr["t"]))
        want = efanim.skin_positions(pos, infl, arm.names, mc)
        got = bf["positions"]
        if len(got) != len(used):
            raise _err("/verify", "vertex_mismatch", "Blender deformed %d vertices but the mesh JSON uses %d positions" % (len(got), len(used)))
        err = [math.dist(got[k], want[i]) for k, i in enumerate(used)]
        moved = [math.dist(pos[i], want[i]) for i in used]
        rows.append({"t": fr["t"], "max_error": max(err), "mean_error": sum(err) / len(err), "max_vertex_displacement": max(moved)})
        worst = max(worst, max(err))
    return {"frames": rows, "max_error": worst, "vertices": len(used), "weight_sum_min": min(wsum), "weight_sum_max": max(wsum),
            "pass": bool(rows) and worst < 1e-3 and min(wsum) > 0.999 and max(wsum) < 1.001,
            "note": "Blender armature deformation (world-space deltas) vs EF linear blend skinning transcribed from the 20.14.17 bytecode; weights as stored"}


# ------------------------------------------------------------------------------------------- the pipeline
def normalize_options(o: Dict[str, Any]) -> Dict[str, Any]:
    d = dict(o)
    d["views"] = list(d.get("views") or DEFAULT_VIEWS)
    for v in d["views"]:
        if v not in VIEW_NAMES:
            raise _err("/views", "unknown_value", "%r is not one of %s" % (v, ", ".join(VIEW_NAMES)))
    d["sheet_views"] = list(d.get("sheet_views") or SHEET_VIEWS)
    for v in d["sheet_views"]:
        if v not in VIEW_NAMES:
            raise _err("/sheet-views", "unknown_value", "%r is not one of %s" % (v, ", ".join(VIEW_NAMES)))
    d["engine"] = d.get("engine") or "workbench"
    if d["engine"] not in ENGINES:
        raise _err("/engine", "unknown_value", "engine must be one of %s" % ", ".join(ENGINES))
    d["light"] = d.get("light") or "studio"
    d["projection"] = d.get("projection") or "ortho"
    d["size"] = int(d.get("size") or DEFAULT_SIZE)
    d["sheet_size"] = int(d.get("sheet_size") or DEFAULT_SHEET_SIZE)
    for k in ("size", "sheet_size"):
        if not 64 <= d[k] <= 2048:
            raise _err("/" + k.replace("_", "-"), "bad_size", "%s must be within 64..2048" % k)
    d["bg"] = parse_color(d.get("bg") or DEFAULT_BG) if not isinstance(d.get("bg"), tuple) else d["bg"]
    d["cols"] = max(1, int(d.get("cols") or 3))
    d["times"] = list(d["times"]) if d.get("times") else [0.0]
    d["pose_ops"] = list(d.get("pose_ops") or [])
    d["grid"] = bool(d.get("grid", True))
    return d


def load_raw(info: dict) -> Canvas:
    """The transparent render of one view: the `.rgba` dump bfk.view wrote next to the PNG (fast), else the PNG."""
    cam = info["camera"]
    w, h = int(cam["width"]), int(cam["height"])
    p = info.get("rgba")
    if p and Path(p).is_file():
        data = Path(p).read_bytes()
        if len(data) == w * h * 4:
            return Canvas(w, h, bytearray(data))
    return read_png(info["file"])


def run_pipeline(source: str, out_dir: str, opts: Dict[str, Any], cache_dir, offline: bool = False) -> Dict[str, Any]:
    """Everything `bossforge blender view` does; `opts` as built by `options_from_args`. Returns the result dict."""
    from . import blender
    t0 = time.time()
    o = normalize_options(opts)
    out = Path(out_dir).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)
    cache = Path(cache_dir)
    warnings: List[Any] = []
    src = resolve_source(source, out, o.get("texture"), cache, offline, o.get("ef_jar"))
    warnings += src.warnings

    anim_frames: List[dict] = []
    clip = arm = None
    anim_key = None
    if o.get("anim"):
        ev = efanim.evaluate(o["anim"], o["times"], cache, o.get("ef_jar"), offline)
        anim_frames, clip, arm = ev["frames"], ev["clip"], ev["armature"]
        anim_key = efanim.normalize_key(o["anim"])
        if any(t > ev["duration"] + 1e-6 for t in o["times"]):
            warnings.append({"path": "/at", "code": "time_clamped", "message": "times beyond the %.3f s clip are held at its last frame" % ev["duration"]})
    if o.get("verify_anim") and not (o.get("anim") and src.bundle is not None):
        raise _err("/verify-anim", "bad_option", "--verify-anim needs --anim and a mesh bundle / spec source")

    ref_views: Dict[str, Any] = {}
    ref_names: List[str] = []
    extra_cams: List[dict] = []
    if o.get("reference_views"):
        ref_views = load_reference_views(src, o.get("reference"))
        ref_names = [n for n in ("front", "back", "right", "left") if n in ref_views]
        extra_cams = reference_cameras(ref_views, ref_names)
    frames = plan_frames(o["views"], o["pose_ops"], bool(o.get("pose_sheet")), o["sheet_views"], o["size"], o["sheet_size"],
                         anim_frames, (anim_key or "anim").split("/")[-1], [c["name"] for c in extra_cams])
    if o.get("verify_anim"):
        for fr in frames:
            if fr["group"] == "anim":
                fr["dump_positions"] = True
    args = {"source": str(src.bundle) if src.bundle else None, "texture": str(src.texture) if src.texture else None, "out": str(out),
            "frames": frames, "cameras": extra_cams, "engine": o["engine"], "light": o["light"], "size": o["size"],
            "projection": o["projection"], "object": o.get("object"), "rig": o.get("rig")}
    res = blender.run_task("view", args, blend=src.blend, timeout=900)
    if not res.get("ok"):
        res = dict(res)
        res.setdefault("source", src.to_dict())
        return res

    bg = o["bg"]
    grid = o["grid"]
    views_dir = out / "views"
    views_dir.mkdir(exist_ok=True)
    by_id = {f["id"]: f for f in res["frames"]}
    planned = {f["id"]: f for f in frames}
    images: Dict[str, Dict[str, str]] = {"main": {}, "pose_sheet": {}, "anim": {}}
    raws: Dict[Tuple[str, str], Canvas] = {}
    metas: Dict[Tuple[str, str], dict] = {}
    composed: Dict[Tuple[str, str], Canvas] = {}
    bg_cache: dict = {}
    for fid, bf in by_id.items():
        pf = planned[fid]
        for vname, info in bf["images"].items():
            raw = load_raw(info)
            raws[(fid, vname)] = raw
            metas[(fid, vname)] = info["camera"]
            if vname.startswith("ref_"):
                continue
            label = vname if pf["group"] == "main" and not o["pose_ops"] else "%s | %s" % (pf["label"], vname)
            img = compose_view(raw, Cam(info["camera"]), bg, label, grid, bg_cache)
            composed[(fid, vname)] = img
            path = views_dir / ("%s.png" % vname if pf["group"] == "main" else "%s_%s.png" % (fid, vname))
            write_png(path, img)
            images[pf["group"]][vname if pf["group"] == "main" else fid + "/" + vname] = str(path)

    result: Dict[str, Any] = {"ok": True, "id": src.id, "source": src.to_dict(), "engine": res.get("engine"), "blender": res.get("blender"),
                              "size": o["size"], "background": "#%02x%02x%02x" % bg, "views": images["main"], "warnings": warnings,
                              "frames": [{"id": f["id"], "label": f["label"], "bbox": f["bbox"], "head": f["head"]} for f in res["frames"]],
                              "cameras": res.get("cameras"), "mesh": res.get("mesh"), "rig": res.get("rig"), "texture": res.get("texture"),
                              "import": res.get("import")}
    title_base = "%s  %s  %s" % (src.id, res.get("engine", ""), "textured" if src.texture else ("blend materials" if src.kind == "blend" else "flat group tints"))
    cs = [composed[("main", v)] for v in o["views"] if ("main", v) in composed]
    if cs:
        mpath = out / "montage.png"
        write_png(mpath, montage(cs, o["cols"], title="%s  POSE: %s" % (title_base, planned["main"]["label"])))
        result["montage"] = str(mpath)
    for group, fname, title in (("pose_sheet", "pose_sheet.png", "POSE SHEET"), ("anim", "anim_sheet.png", "ANIMATION " + (anim_key or ""))):
        fids = [f["id"] for f in frames if f["group"] == group]
        if not fids:
            continue
        cs = [composed[(fid, v)] for fid in fids for v in o["sheet_views"]]
        spath = out / fname
        write_png(spath, montage(cs, len(o["sheet_views"]), gap=4, title="%s  %s" % (title_base, title)))
        result["pose_sheet" if group == "pose_sheet" else "anim_sheet"] = str(spath)
    if ref_names:
        rows, metrics = [], {}
        for name in ref_names:
            cam_meta = metas[("main", "ref_" + name)]
            row, met = reference_cell(name, ref_views[name], raws[("main", "ref_" + name)], Cam(cam_meta), bg, grid)
            rpath = views_dir / ("ref_%s.png" % name)
            write_png(rpath, row)
            met["image"] = str(rpath)
            met["px_per_block"] = ref_views[name].px_per_block
            metrics[name] = met
            rows.append(row)
        cpath = out / "reference_compare.png"
        write_png(cpath, montage(rows, 1, gap=4, title="%s  REFERENCE COMPARE (RENDER VS REFERENCE AT THE REFERENCE SCALE)" % title_base))
        result["reference_compare"] = str(cpath)
        result["reference"] = metrics
    if o.get("verify_anim") and clip is not None and arm is not None and src.bundle is not None:
        result["verification"] = verify_frames(src.bundle, clip, arm, frames, by_id)
        if not result["verification"]["pass"]:
            result["ok"] = False
            result["errors"] = [{"path": "/verify-anim", "code": "verification_failed", "message": "Blender deformation differs from EF skinning by %.3g blocks (limit 1e-3)" % result["verification"]["max_error"]}]
    if anim_key:
        result["animation"] = {"key": anim_key, "duration": clip.duration if clip else None, "times": o["times"]}
    result["seconds"] = round(time.time() - t0, 2)
    (out / "view.json").write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return result


def options_from_args(args) -> Dict[str, Any]:
    pose_ops = parse_pose(getattr(args, "pose", None))
    return {
        "texture": getattr(args, "texture", None),
        "views": parse_list(getattr(args, "views", None), VIEW_NAMES, "/views", DEFAULT_VIEWS),
        "sheet_views": parse_list(getattr(args, "sheet_views", None), VIEW_NAMES, "/sheet-views", SHEET_VIEWS),
        "pose_ops": pose_ops, "pose_sheet": bool(getattr(args, "pose_sheet", False)),
        "anim": getattr(args, "anim", None), "times": parse_times(getattr(args, "at", None)),
        "verify_anim": bool(getattr(args, "verify_anim", False)),
        "engine": getattr(args, "engine", None), "light": getattr(args, "light", None), "projection": getattr(args, "projection", None),
        "size": getattr(args, "size", None), "sheet_size": getattr(args, "sheet_size", None), "bg": getattr(args, "bg", None),
        "reference_views": bool(getattr(args, "reference_views", False)), "reference": getattr(args, "reference", None),
        "cols": getattr(args, "cols", None), "grid": not getattr(args, "no_grid", False),
        "object": getattr(args, "object", None), "rig": getattr(args, "rig", None), "ef_jar": getattr(args, "ef_jar", None),
    }


def run_view(args) -> int:
    """CLI handler of `bossforge blender view` (registered by cli.py)."""
    from . import cli, efassets
    try:
        cache = Path(args.cache_dir) if getattr(args, "cache_dir", None) else efassets.default_cache_dir()
        res = run_pipeline(args.source, args.out, options_from_args(args), cache, bool(getattr(args, "offline", False)))
    except BossForgeError as e:
        return cli._fail([e.err])
    return cli._out(res, 0 if res.get("ok") else 1)


def render(bundle_dir, texture, out_dir, cache_dir=None, offline: bool = False, **opts) -> Dict[str, Any]:
    """Python helper for other tools: render a bundle (directory or `.efmesh.json`) with `texture` into `out_dir`.

    `opts`: views (list), pose (str like "arm_r=60"), pose_sheet (bool), anim / times, engine, light, projection, size,
    sheet_size, bg ("#rrggbb"), reference_views (needs a spec source), cols, grid. Returns the same dict as the CLI."""
    from . import efassets
    o = {"texture": str(texture) if texture else None, "pose_ops": parse_pose(opts.pop("pose", None))}
    for k in ("views", "sheet_views"):
        if k in opts:
            o[k] = list(opts.pop(k))
    o.update(opts)
    return run_pipeline(str(bundle_dir), str(out_dir), o, Path(cache_dir) if cache_dir else efassets.default_cache_dir(), offline)
